//! Wire types for the agent <-> broker intent protocol.
//!
//! See `docs/PROTOCOL.md` for the human-readable spec. This crate is the
//! machine-readable contract. Nothing in here talks to the network, the
//! filesystem, or the clock. It is pure data.

use serde::{Deserialize, Serialize};

/// Actions an agent may ask the broker to perform.
///
/// The agent can *ask* for any of these. It cannot perform any of them.
/// The broker decides.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Action {
    ReadFile,
    WriteFile,
    HttpGet,
    Exec,
    /// Ask the broker to run one model completion. The agent never holds the
    /// model endpoint or API key; the broker does.
    LlmChat,
    /// Send a message to another agent in the same group. The broker routes it.
    SendMessage,
    /// Collect the messages waiting for this agent.
    RecvMessage,
    /// Start a child agent in its own sandbox, in the same group.
    SpawnAgent,
}

/// A request from the agent to the broker.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Intent {
    /// UUID v4, generated by the agent, echoed by the broker.
    pub id: String,
    pub action: Action,
    /// Action-specific parameters. Shape is defined per-action in PROTOCOL.md.
    pub params: serde_json::Value,
    /// Free-text. Logged, never trusted, never parsed for control flow.
    #[serde(default)]
    pub justification: String,
}

/// The broker's answer. Every intent gets exactly one verdict.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VerdictKind {
    /// Perform the action, return the result.
    Allow,
    /// Refuse. `reason` explains why.
    Deny,
    /// Hold and ask a human. Human's answer becomes allow/deny.
    ApproveRequired,
    /// Perform a modified version of the action (broker rewrites params).
    Transform,
    /// Return what *would* happen without performing it.
    DryRun,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Verdict {
    /// Echo of `Intent::id`.
    pub id: String,
    pub verdict: VerdictKind,
    /// Action result if `Allow`/`Transform`, else null.
    pub result: serde_json::Value,
    /// Human-readable reason (policy path, denial cause, etc.).
    pub reason: String,
    /// Ed25519-signed capability token. Only present when `verdict == Allow`.
    /// Agent never sees the signing key; agent only receives the token.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub token: Option<String>,
}

impl Intent {
    /// Convenience constructor. Generates a fresh UUID, empty justification.
    pub fn new(action: Action, params: serde_json::Value) -> Self {
        Self {
            id: uuid::Uuid::new_v4().to_string(),
            action,
            params,
            justification: String::new(),
        }
    }

    /// Builder-style: attach a justification.
    pub fn with_justification(mut self, j: impl Into<String>) -> Self {
        self.justification = j.into();
        self
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn intent_roundtrips_through_json() {
        let i = Intent::new(Action::ReadFile, json!({ "path": "/tmp/x" }))
            .with_justification("user asked me to summarize it");
        let s = serde_json::to_string(&i).unwrap();
        let back: Intent = serde_json::from_str(&s).unwrap();
        assert_eq!(i, back);
    }

    #[test]
    fn action_serializes_as_snake_case() {
        let i = Intent::new(Action::HttpGet, json!({ "url": "https://example.com" }));
        let v: serde_json::Value = serde_json::to_value(&i).unwrap();
        assert_eq!(v["action"], "http_get");
    }

    #[test]
    fn verdict_omits_token_when_none() {
        let v = Verdict {
            id: "test".into(),
            verdict: VerdictKind::Deny,
            result: json!(null),
            reason: "policy: no".into(),
            token: None,
        };
        let s = serde_json::to_string(&v).unwrap();
        assert!(
            !s.contains("token"),
            "token field must be omitted when None: {s}"
        );
        assert!(s.contains("\"verdict\":\"deny\""));
    }

    #[test]
    fn empty_justification_is_accepted() {
        // Justification is optional on the wire; agent may omit it entirely.
        let wire = r#"{"id":"a","action":"exec","params":{"cmd":"ls"}}"#;
        let i: Intent = serde_json::from_str(wire).unwrap();
        assert_eq!(i.justification, "");
    }
}
